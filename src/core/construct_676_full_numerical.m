function Coefs = construct_676_full_numerical(theta1, theta2, theta3, theta4, t1, t2, t3)
    T = zeros(22, 22); Y = zeros(22, 1);
    T(1,1) = 1; Y(1) = theta1; T(2,2) = 1; T(3,3) = 2; T(4,4) = 6; T(5,5) = 24;
    T(6,1:7) = [1, t1, t1^2, t1^3, t1^4, t1^5, t1^6]; Y(6) = theta2;  
    T(7,8) = 1; Y(7) = theta2;        
    T(8,8:15) = [1, t2, t2^2, t2^3, t2^4, t2^5, t2^6, t2^7]; Y(8) = theta3;  
    T(9,16) = 1; Y(9) = theta3;       
    T(10,16:22) = [1, t3, t3^2, t3^3, t3^4, t3^5, t3^6]; Y(10) = theta4;  
    T(11,2:7) = [1, 2*t1, 3*t1^2, 4*t1^3, 5*t1^4, 6*t1^5]; T(11,9) = -1;  
    T(12,3:7) = [2, 6*t1, 12*t1^2, 20*t1^3, 30*t1^4]; T(12,10) = -2;     
    T(13,4:7) = [6, 24*t1, 60*t1^2, 120*t1^3]; T(13,11) = -6;            
    T(14,5:7) = [24, 120*t1, 360*t1^2]; T(14,12) = -24;                  
    T(15,9:15) = [1, 2*t2, 3*t2^2, 4*t2^3, 5*t2^4, 6*t2^5, 7*t2^6]; T(15,17) = -1;  
    T(16,10:15) = [2, 6*t2, 12*t2^2, 20*t2^3, 30*t2^4, 42*t2^5]; T(16,18) = -2;   
    T(17,11:15) = [6, 24*t2, 60*t2^2, 120*t2^3, 210*t2^4]; T(17,19) = -6;         
    T(18,12:15) = [24, 120*t2, 360*t2^2, 840*t2^3]; T(18,20) = -24;               
    T(19,17:22) = [1, 2*t3, 3*t3^2, 4*t3^3, 5*t3^4, 6*t3^5]; 
    T(20,18:22) = [2, 6*t3, 12*t3^2, 20*t3^3, 30*t3^4]; 
    T(21,19:22) = [6, 24*t3, 60*t3^2, 120*t3^3]; 
    T(22,20:22) = [24, 120*t3, 360*t3^2]; 
    X = T \ Y;
    Coefs.a = X(7:-1:1)'; Coefs.b = X(15:-1:8)'; Coefs.c = X(22:-1:16)';
end
